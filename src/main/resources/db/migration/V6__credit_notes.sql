-- Invoices are never deleted or edited. Mistakes, returns and cancellations are handled by issuing a
-- credit note against specific invoice lines, which reduces what the customer owes.

alter table invoice add column amount_credited numeric(12, 2) not null default 0;
alter table invoice drop constraint ck_invoice_paid;
alter table invoice add constraint ck_invoice_settlement
    check (amount_paid >= 0 and amount_credited >= 0 and amount_paid + amount_credited <= gross_total);

alter table invoice_line add column credited_quantity integer not null default 0;
alter table invoice_line add constraint ck_invoice_line_credited
    check (credited_quantity >= 0 and credited_quantity <= quantity);

create table credit_note (
    id                 bigint generated by default as identity primary key,
    credit_note_number varchar(30)    not null,
    invoice_id         bigint         not null references invoice (id),
    issue_date         date           not null,
    reason             varchar(500)   not null,
    net_total          numeric(12, 2) not null,
    vat_total          numeric(12, 2) not null,
    gross_total        numeric(12, 2) not null check (gross_total > 0),
    created_at         timestamptz    not null,
    constraint uk_credit_note_number unique (credit_note_number)
);

create index ix_credit_note_invoice_id on credit_note (invoice_id);

create table credit_note_line (
    id              bigint generated by default as identity primary key,
    credit_note_id  bigint         not null references credit_note (id),
    invoice_line_id bigint         not null references invoice_line (id),
    sku             varchar(50)    not null,
    description     varchar(200)   not null,
    quantity        integer        not null check (quantity > 0),
    unit_price      numeric(12, 2) not null,
    vat_rate        varchar(10)    not null,
    net_amount      numeric(12, 2) not null,
    vat_amount      numeric(12, 2) not null,
    gross_amount    numeric(12, 2) not null
);

create index ix_credit_note_line_credit_note_id on credit_note_line (credit_note_id);
