create table invoice (
    id                 bigint generated by default as identity primary key,
    invoice_number     varchar(30)    not null,
    order_id           bigint         not null references orders (id),
    customer_id        bigint         not null references customer (id),
    customer_name      varchar(200)   not null,
    billing_address    varchar(500)   not null,
    status             varchar(20)    not null check (status in ('ISSUED', 'PART_PAID', 'PAID', 'OVERDUE', 'VOID')),
    issue_date         date           not null,
    due_date           date           not null,
    payment_terms_days integer        not null,
    net_total          numeric(12, 2) not null,
    vat_total          numeric(12, 2) not null,
    gross_total        numeric(12, 2) not null,
    amount_paid        numeric(12, 2) not null default 0,
    created_at         timestamptz    not null,
    updated_at         timestamptz    not null,
    version            bigint         not null default 0,
    constraint uk_invoice_number unique (invoice_number),
    constraint uk_invoice_order unique (order_id),
    constraint ck_invoice_due_after_issue check (due_date >= issue_date),
    constraint ck_invoice_gross check (gross_total = net_total + vat_total),
    constraint ck_invoice_paid check (amount_paid >= 0 and amount_paid <= gross_total)
);

create index ix_invoice_customer_id on invoice (customer_id);
create index ix_invoice_status_due_date on invoice (status, due_date);
create index ix_invoice_issue_date on invoice (issue_date);

create table invoice_line (
    id           bigint generated by default as identity primary key,
    invoice_id   bigint         not null references invoice (id),
    line_number  integer        not null,
    sku          varchar(50)    not null,
    description  varchar(200)   not null,
    quantity     integer        not null check (quantity > 0),
    unit_price   numeric(12, 2) not null,
    vat_rate     varchar(10)    not null check (vat_rate in ('STANDARD', 'REDUCED', 'ZERO')),
    net_amount   numeric(12, 2) not null,
    vat_amount   numeric(12, 2) not null,
    gross_amount numeric(12, 2) not null,
    constraint uk_invoice_line_number unique (invoice_id, line_number)
);
