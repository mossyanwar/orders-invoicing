-- Append-only record of who changed what. Rows are written in the same transaction as the change
-- they describe, so a rolled-back change leaves no audit row and a committed one always has one.
create table audit_event (
    id          bigint generated by default as identity primary key,
    occurred_at timestamptz   not null,
    actor       varchar(100)  not null,
    entity_type varchar(30)   not null,
    entity_id   bigint        not null,
    action      varchar(50)   not null,
    from_status varchar(20),
    to_status   varchar(20),
    detail      varchar(1000)
);

create index ix_audit_event_entity on audit_event (entity_type, entity_id, id);
