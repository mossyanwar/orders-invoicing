create table payment (
    id          bigint generated by default as identity primary key,
    customer_id bigint         not null references customer (id),
    amount      numeric(12, 2) not null check (amount > 0),
    received_on date           not null,
    method      varchar(20)    not null check (method in ('BANK_TRANSFER', 'CARD', 'CHEQUE')),
    reference   varchar(100),
    created_at  timestamptz    not null
);

create index ix_payment_customer_id on payment (customer_id);

create table payment_allocation (
    id             bigint generated by default as identity primary key,
    payment_id     bigint         not null references payment (id),
    invoice_id     bigint         not null references invoice (id),
    invoice_number varchar(30)    not null,
    amount         numeric(12, 2) not null check (amount > 0),
    constraint uk_payment_allocation unique (payment_id, invoice_id)
);

create index ix_payment_allocation_invoice_id on payment_allocation (invoice_id);
