create table orders (
    id          bigint generated by default as identity primary key,
    customer_id bigint      not null references customer (id),
    status      varchar(20) not null check (status in ('DRAFT', 'CONFIRMED', 'FULFILLED', 'INVOICED', 'CANCELLED')),
    created_at  timestamptz not null,
    updated_at  timestamptz not null,
    version     bigint      not null default 0
);

create index ix_orders_customer_id on orders (customer_id);
create index ix_orders_status on orders (status);

-- sku, description, unit price and vat rate are copied from the product when the line is added,
-- so later catalogue changes do not alter an order that is already in progress
create table order_line (
    id          bigint generated by default as identity primary key,
    order_id    bigint         not null references orders (id) on delete cascade,
    product_id  bigint         not null references product (id),
    sku         varchar(50)    not null,
    description varchar(200)   not null,
    quantity    integer        not null check (quantity > 0),
    unit_price  numeric(12, 2) not null check (unit_price >= 0),
    vat_rate    varchar(10)    not null check (vat_rate in ('STANDARD', 'REDUCED', 'ZERO'))
);

create index ix_order_line_order_id on order_line (order_id);
